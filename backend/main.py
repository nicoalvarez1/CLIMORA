from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware

app = FastAPI()

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)


def buscar_ciutat(nom):
    nom = nom.strip().casefold()

    for ciutat in cities:
        if ciutat["name"].casefold() == nom:
            return ciutat

    return None


def preparar_ciutat(ciutat):
    return {
        "nombre": ciutat["name"].title(),
        "pais": ciutat["country"].title(),
        "descripcion": ciutat["climate_type"],
        "poblacion_millones": round(
            ciutat["population"] / 1_000_000, 2
        ),
        "temperatura_media": ciutat["avg_temp_year"],
        "precipitacion_mm": ciutat["precipitation_mm"],
        "horas_sol": ciutat["sunshine_hours"],
        "humedad": ciutat["humidity_percent"],
        "clima": ciutat["climate_code"]
    }


@app.get("/comparar")
def comparar(ciudad1: str, ciudad2: str):
    primera = buscar_ciutat(ciudad1)
    segona = buscar_ciutat(ciudad2)

    if primera is None:
        raise HTTPException(
            status_code=404,
            detail=f"No s'ha trobat la ciutat: {ciudad1}"
        )

    if segona is None:
        raise HTTPException(
            status_code=404,
            detail=f"No s'ha trobat la ciutat: {ciudad2}"
        )

    if primera["name"].casefold() == segona["name"].casefold():
        raise HTTPException(
            status_code=400,
            detail="Selecciona dues ciutats diferents."
        )

    ciutat_a = preparar_ciutat(primera)
    ciutat_b = preparar_ciutat(segona)

    comparacion = [
        {
            "caracteristica": "Temperatura mitjana anual",
            "valor1": f'{ciutat_a["temperatura_media"]} °C',
            "valor2": f'{ciutat_b["temperatura_media"]} °C',
            "ganador": ""
        },
        {
            "caracteristica": "Precipitació anual",
            "valor1": f'{ciutat_a["precipitacion_mm"]} mm',
            "valor2": f'{ciutat_b["precipitacion_mm"]} mm',
            "ganador": ""
        },
        {
            "caracteristica": "Hores de sol anuals",
            "valor1": str(ciutat_a["horas_sol"]),
            "valor2": str(ciutat_b["horas_sol"]),
            "ganador": ""
        },
        {
            "caracteristica": "Humitat",
            "valor1": f'{ciutat_a["humedad"]}%',
            "valor2": f'{ciutat_b["humedad"]}%',
            "ganador": ""
        },
        {
            "caracteristica": "Població",
            "valor1": f'{primera["population"]:,}'.replace(",", "."),
            "valor2": f'{segona["population"]:,}'.replace(",", "."),
            "ganador": ""
        }
    ]

    conclusion = (
        f'{ciutat_a["nombre"]} té clima {ciutat_a["descripcion"]}. '
        f'{ciutat_b["nombre"]} té clima {ciutat_b["descripcion"]}.'
    )

    return {
        "ciudades": [ciutat_a, ciutat_b],
        "comparacion": comparacion,
        "conclusion": conclusion
    }

